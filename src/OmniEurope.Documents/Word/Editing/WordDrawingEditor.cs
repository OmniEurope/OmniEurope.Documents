using System.Globalization;
using System.Xml.Linq;
using OmniEurope.Documents.Internal;
using OmniEurope.Documents.Word.Writing;
using static OmniEurope.Documents.Word.WordXml;

namespace OmniEurope.Documents.Word.Editing;

/// <summary>
/// Inserts, replaces and removes the drawings of one paragraph in the package XML. The drawing XML is the one
/// <see cref="WordDrawingWriter"/> and <see cref="WordInkWriter"/> write for a <see cref="WordDocument"/>, so a
/// document edited here and a document written from the model are the same markup.
/// </summary>
internal sealed class WordDrawingEditor(OpcPackage package, string mainPart, string partName, XElement paragraph)
{
    // Word starts the z-order of anchored shapes here and steps by this much.
    private const long FirstRelativeHeight = 251658240;
    private const long RelativeHeightStep = 1024;
    private const long MaxRelativeHeight = uint.MaxValue;

    private static readonly string[] StoryTypes = [HeaderType, FooterType, FootnotesType, EndnotesType, CommentsType];

    // The conventional prefixes for a fragment the document root does not declare: the XML stays readable (a prefix
    // left undeclared would be generated by the serializer, still valid).
    private static readonly Dictionary<string, string> Prefixes = new(StringComparer.Ordinal)
    {
        [Wp.NamespaceName] = "wp",
        [A.NamespaceName] = "a",
        [Pic.NamespaceName] = "pic",
        [R.NamespaceName] = "r",
        [Mc.NamespaceName] = "mc",
        ["http://schemas.microsoft.com/office/word/2010/wordml"] = "w14",
        ["http://schemas.microsoft.com/office/word/2010/wordprocessingInk"] = "wpi",
    };

    public List<WordDrawingInfo> List() => WordDrawingScanner.Scan(paragraph).Select((d, i) => d.Info(i)).ToList();

    public WordDrawingInfo Insert(WordDrawingContent content, WordDrawingPlacement placement)
    {
        var (width, height) = Size(placement, content.DefaultWidth, content.DefaultHeight);
        var run = new XElement(W + "r", new XElement(W + "rPr", new XElement(W + "noProof")), Build(content, width, height, Floating(placement), NextRelativeHeight()));
        var index = WordDrawingScanner.Scan(paragraph).Count;
        paragraph.Add(run);
        Declare(run);
        return List()[index];
    }

    public WordDrawingInfo Replace(int index, WordDrawingContent content, WordDrawingPlacement? placement)
    {
        var old = At(index);
        var (width, height) = Size(placement, old.Width, old.Height);
        var oldHeight = old.Frame is { } frame && long.TryParse((string?)frame.Attribute("relativeHeight"), NumberStyles.None, CultureInfo.InvariantCulture, out var z) ? z : (long?)null;
        var element = Build(content, width, height, placement is null ? old.Floating : Floating(placement), oldHeight ?? NextRelativeHeight());
        var references = References(old.Unit);
        old.Unit.ReplaceWith(element);
        Declare(element);
        Release(references);
        return List()[index];
    }

    public void Remove(int index)
    {
        var old = At(index);
        var references = References(old.Unit);
        var run = old.Unit.Parent;
        old.Unit.Remove();
        if (run is { } holder && holder.Name == W + "r" && holder.Elements().All(e => e.Name == W + "rPr"))
        {
            var wrapper = holder.Parent;
            holder.Remove();
            WordRunBuilder.RemoveIfEmpty(paragraph, wrapper);
        }

        Release(references);
    }

    private ScannedDrawing At(int index)
    {
        var drawings = WordDrawingScanner.Scan(paragraph);
        ArgumentOutOfRangeException.ThrowIfNegative(index);
        ArgumentOutOfRangeException.ThrowIfGreaterThanOrEqual(index, drawings.Count);
        return drawings[index];
    }

    private static WordFloatingPosition Floating(WordDrawingPlacement placement) =>
        new(placement.OffsetX, "column", placement.OffsetY, "paragraph", WordWrap.None, placement.BehindText);

    private static (double Width, double Height) Size(WordDrawingPlacement? placement, double defaultWidth, double defaultHeight)
    {
        var (width, height) = (placement?.Width ?? defaultWidth, placement?.Height ?? defaultHeight);
        if (!double.IsFinite(width) || width <= 0 || !double.IsFinite(height) || height <= 0)
        {
            throw new ArgumentOutOfRangeException(nameof(placement), "A drawing needs a positive, finite width and height.");
        }

        return (width, height);
    }

    // The drawing for the content: new parts and relationships, then the XML the writers produce for the model shape.
    private XElement Build(WordDrawingContent content, double width, double height, WordFloatingPosition? floating, long relativeHeight)
    {
        var id = NextDrawingId();
        return content.Kind == WordDrawingKind.Ink ? Ink(content, id, width, height, floating, relativeHeight) : Picture(content, id, width, height, floating, relativeHeight);
    }

    private XElement Ink(WordDrawingContent content, int id, double width, double height, WordFloatingPosition? floating, long relativeHeight)
    {
        var ink = new WordInk(width, height) { Floating = floating };
        ink.Strokes.AddRange(content.Strokes);
        var name = package.UniqueName("word/ink/ink", "xml");
        package.SetXml(name, new XDocument(new XDeclaration("1.0", "UTF-8", "yes"), WordInkWriter.Part(ink)), InkContentType);
        return WordInkWriter.Ink(id, ink, package.AddRelationship(partName, InkType, name), relativeHeight);
    }

    private XElement Picture(WordDrawingContent content, int id, double width, double height, WordFloatingPosition? floating, long relativeHeight)
    {
        var name = package.UniqueName("word/media/image", "png");
        package.SetBytes(name, content.PngData!, "image/png");
        var picture = new WordPicture(new WordImage(content.PngData!, "image/png"), width, height) { Floating = floating };
        return WordDrawingWriter.Picture(id, picture, package.AddRelationship(partName, ImageType, name), relativeHeight);
    }

    // The parts holding text, whose drawings share one id space.
    private IEnumerable<XElement> TextRoots()
    {
        var parts = package.Relationships(mainPart).Where(r => !r.External && StoryTypes.Contains(r.Type)).Select(r => r.Target).Prepend(mainPart).Append(partName);
        return parts.Distinct(StringComparer.OrdinalIgnoreCase).Select(p => package.GetXml(p)?.Root).OfType<XElement>();
    }

    private int NextDrawingId()
    {
        var used = TextRoots().SelectMany(r => r.Descendants(Wp + "docPr")).Select(e => int.TryParse((string?)e.Attribute("id"), NumberStyles.None, CultureInfo.InvariantCulture, out var id) ? id : 0).ToHashSet();
        var highest = used.Count == 0 ? 0 : used.Max();
        return highest < int.MaxValue ? highest + 1 : Enumerable.Range(1, int.MaxValue).First(candidate => !used.Contains(candidate));
    }

    // Above every anchored shape of the parts: a new drawing lies over the others unless it is behind the text.
    private long NextRelativeHeight()
    {
        var highest = TextRoots().SelectMany(r => r.Descendants(Wp + "anchor"))
            .Select(a => long.TryParse((string?)a.Attribute("relativeHeight"), NumberStyles.None, CultureInfo.InvariantCulture, out var z) ? z : 0)
            .DefaultIfEmpty(0).Max();
        return Math.Min(MaxRelativeHeight, Math.Max(highest, FirstRelativeHeight) + RelativeHeightStep);
    }

    // The relationship ids a removed drawing named: images, ink, charts, links.
    private static List<string> References(XElement unit) =>
        unit.DescendantsAndSelf().Attributes().Where(a => a.Name.Namespace == R).Select(a => a.Value).Distinct(StringComparer.Ordinal).ToList();

    // Drops the relationships no markup of the part names any more, then the parts nothing relates to.
    private void Release(List<string> references)
    {
        var root = package.GetXml(partName)?.Root;
        foreach (var id in references)
        {
            if (root is not null && root.DescendantsAndSelf().Attributes().Any(a => a.Name.Namespace == R && a.Value == id))
            {
                continue;
            }

            var relationship = package.Relationships(partName).Find(r => r.Id == id);
            if (relationship is null)
            {
                continue;
            }

            package.RemoveRelationship(partName, id);
            if (!relationship.External)
            {
                WordPackageParts.Release(package, relationship.Target);
            }
        }
    }

    private void Declare(XElement fragment)
    {
        foreach (var ns in fragment.DescendantsAndSelf().SelectMany(e => e.Attributes().Select(a => a.Name.Namespace).Append(e.Name.Namespace)).Distinct().ToList())
        {
            if (Prefixes.TryGetValue(ns.NamespaceName, out var prefix) && paragraph.GetPrefixOfNamespace(ns) is null && paragraph.GetNamespaceOfPrefix(prefix) is null)
            {
                fragment.SetAttributeValue(XNamespace.Xmlns + prefix, ns.NamespaceName);
            }
        }
    }
}
